OUTPUT_PATH = r'C:\Users\张三\Desktop\论文初稿\acspc_输出_改稿v6.docx'

doc = Document(PAPER_PATH)
updates = []

def replace_in_paragraph(idx, old, new, reason):
    """在指定段落中替换文本"""
    p = doc.paragraphs[idx]
    if old in p.text:
        replaced = False
        for run in p.runs:
            if old in run.text:
                run.text = run.text.replace(old, new)
                replaced = True
                break
        if not replaced:
            full_text = p.text
            new_full = full_text.replace(old, new)
            if p.runs:
                p.runs[0].text = new_full
                for run in p.runs[1:]:
                    run.text = ''
        updates.append(f'[{idx}] {reason}')
        return True
    else:
        print(f'  警告: [{idx}] 未找到 "{old[:50]}..."')
        return False

